import type { BookRow, HighlightRow } from "./store";

/** "Outlive: The Science and Art of Longevity" -> "outlive" */
export function slugify(title: string): string {
	const main = title.split(/[:([]/)[0].trim() || title;
	const slug = main
		.normalize("NFKD")
		.replace(/[̀-ͯ]/g, "")
		.toLowerCase()
		.replace(/['’]/g, "")
		.replace(/[^a-z0-9]+/g, "-")
		.replace(/^-+|-+$/g, "")
		.slice(0, 60)
		.replace(/-+$/, "");
	return slug || "untitled";
}

export function formatDate(ms: number | null, timeZone: string): string {
	if (!ms) return "";
	// en-CA formats as YYYY-MM-DD
	return new Intl.DateTimeFormat("en-CA", {
		timeZone,
		year: "numeric",
		month: "2-digit",
		day: "2-digit",
	}).format(new Date(ms));
}

const quote = (text: string) =>
	text
		.split(/\r?\n/)
		.map((line) => `> ${line}`.trimEnd())
		.join("\n");

/** The markdown file for one book: `<slug>/highlights.md`. */
export function renderBook(
	book: BookRow,
	highlights: HighlightRow[],
	timeZone: string,
): string {
	const lines: string[] = [`# ${book.title}`, ""];
	if (book.authors) lines.push(`*${book.authors}*`, "");
	lines.push(
		`${highlights.length} highlight${highlights.length === 1 ? "" : "s"} · ASIN ${book.asin}`,
		"",
		"<!-- Generated by mcp-server from Kindle. Edits here are overwritten on the next sync. -->",
		"",
	);

	for (const h of highlights) {
		lines.push("---", "");
		if (h.text) {
			lines.push(quote(h.truncated ? `${h.text}…` : h.text), "");
		}
		if (h.note) lines.push(`**Note:** ${h.note}`, "");
		const meta = [
			h.location !== null ? `Location ${h.location}` : "",
			formatDate(h.modified_at, timeZone),
			h.truncated ? "preview only" : "",
		].filter(Boolean);
		if (meta.length) lines.push(`<sub>${meta.join(" · ")}</sub>`, "");
	}
	return `${lines.join("\n").trimEnd()}\n`;
}

export const filePathFor = (slug: string) => `${slug}/highlights.md`;
